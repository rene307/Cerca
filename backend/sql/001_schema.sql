BEGIN;
CREATE TABLE IF NOT EXISTS negocios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datos JSONB NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT negocio_nombre CHECK (jsonb_typeof(datos->'nombre') = 'string')
);
CREATE INDEX IF NOT EXISTS idx_negocios_comuna ON negocios ((datos->>'comuna'));
CREATE INDEX IF NOT EXISTS idx_negocios_categoria ON negocios ((datos->>'categoria'));
CREATE TABLE IF NOT EXISTS suscriptores (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    canal TEXT NOT NULL CHECK (canal IN ('email','whatsapp')),
    nombre TEXT NOT NULL,
    contacto TEXT NOT NULL,
    comuna TEXT NOT NULL,
    intereses TEXT[] NOT NULL DEFAULT '{}',
    intencion TEXT NOT NULL CHECK (intencion IN ('ahora','pronto','explorando')),
    frecuencia TEXT NOT NULL CHECK (frecuencia IN ('diaria','semanal','mensual')),
    contenido TEXT NOT NULL CHECK (contenido IN ('promociones','actualizaciones','ambas')),
    estado TEXT NOT NULL DEFAULT 'pendiente_verificacion'
         CHECK (estado IN ('pendiente_verificacion','confirmado','baja')),
    consentimiento_en TIMESTAMPTZ NOT NULL,
    consentimiento_version TEXT NOT NULL DEFAULT 'v1',
    baja_token_hash TEXT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(canal, contacto)
);
CREATE INDEX IF NOT EXISTS idx_segmentacion_cerca ON suscriptores (estado, comuna, frecuencia, intencion, canal);
CREATE INDEX IF NOT EXISTS idx_suscriptores_intereses ON suscriptores USING GIN (intereses);
CREATE TABLE IF NOT EXISTS eventos (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tipo TEXT NOT NULL CHECK(tipo IN ('visita','busqueda','categoria','ficha','whatsapp','web','ruta','telefono','favorito','suscripcion','gps','campana')),
    negocio_id BIGINT REFERENCES negocios(id) ON DELETE SET NULL,
    comuna TEXT, categoria TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_eventos_fecha ON eventos (creado_en);
CREATE INDEX IF NOT EXISTS idx_eventos_negocio ON eventos (negocio_id, creado_en);
CREATE TABLE IF NOT EXISTS opiniones (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    negocio_id BIGINT NOT NULL REFERENCES negocios(id) ON DELETE CASCADE,
    dispositivo_hash TEXT NOT NULL,
    estrellas SMALLINT NOT NULL CHECK(estrellas BETWEEN 1 AND 5),
    motivos TEXT[] NOT NULL DEFAULT '{}',
    comentario TEXT NOT NULL DEFAULT '',
    estado TEXT NOT NULL DEFAULT 'pendiente' CHECK(estado IN ('pendiente','resuelto')),
    respuesta TEXT NOT NULL DEFAULT '',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(negocio_id,dispositivo_hash)
);
CREATE INDEX IF NOT EXISTS idx_opiniones_negocio ON opiniones(negocio_id);
CREATE TABLE IF NOT EXISTS campanas (
    frecuencia TEXT PRIMARY KEY CHECK(frecuencia IN ('diaria','semanal','mensual','anual')),
    programacion JSONB NOT NULL,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Un solo código activo y válido durante 6 minutos; los códigos se guardan como HMAC.
CREATE TABLE IF NOT EXISTS codigos_acceso_admin (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  correo TEXT NOT NULL,
  sal TEXT NOT NULL,
  codigo_hash TEXT NOT NULL,
  intentos SMALLINT NOT NULL DEFAULT 0 CHECK(intentos BETWEEN 0 AND 5),
  expira_en TIMESTAMPTZ NOT NULL,
  usado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_codigos_acceso_admin_correo ON codigos_acceso_admin(correo,id DESC);
CREATE TABLE IF NOT EXISTS solicitudes (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 texto TEXT NOT NULL CHECK (char_length(texto) BETWEEN 5 AND 500),
 comuna TEXT NOT NULL CHECK (char_length(comuna) BETWEEN 1 AND 90),
 categoria TEXT NOT NULL DEFAULT 'Por clasificar',
 estado TEXT NOT NULL DEFAULT 'nueva' CHECK (estado IN ('nueva','atendida','cerrada')),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_solicitudes_estado_fecha ON solicitudes (estado,creado_en DESC);
COMMIT;
